"""Approved Manim scene templates.

Security model (development rules #13/#14):
  * Scene plans are DATA. They are validated against a strict allow-list of keys,
    types, enumerations and length caps below.
  * The Manim source is produced by *our* template code — model output is only ever
    embedded as a Python literal (repr of a validated dict), never executed.
  * Rendering runs manim as a subprocess with a timeout and no shell.
"""
from __future__ import annotations

import json
import re
import shutil
import sys
import importlib.util
from pathlib import Path
from typing import Any

SCENE_TYPES = {"title", "bullet_list", "formula", "diagram_flow", "comparison", "quote", "summary"}
COMPLEXITIES = {"beginner", "intermediate", "advanced"}

_MAX_STR = 300
_MAX_BULLETS = 6
_MAX_SCENES = 8


class PlanValidationError(ValueError):
    pass


def _ffmpeg_available() -> bool:
    """PATH lookup first, then the explicit ffmpeg_bin_path from .env (if set)."""
    if shutil.which("ffmpeg"):
        return True
    from ..config import settings

    configured = settings.ffmpeg_bin_path.strip()
    if not configured:
        return False
    candidate = Path(configured)
    if candidate.is_dir():
        # .env may name the folder that contains the binaries.
        candidate = candidate / "ffmpeg.exe"
    elif candidate.suffix == "":
        candidate = candidate.with_suffix(".exe")
    return candidate.exists()


def renderer_status() -> dict[str, bool]:
    return {"manim": importlib.util.find_spec("manim") is not None, "ffmpeg": _ffmpeg_available()}


def _clean_str(value: Any, cap: int = _MAX_STR) -> str:
    if value is None:
        return ""
    if not isinstance(value, (str, int, float)):
        raise PlanValidationError(f"Expected text, got {type(value).__name__}")
    text = re.sub(r"[\x00-\x08\x0b-\x1f]", "", str(value)).strip()
    return text[:cap]


def validate_scene_plan(plan: Any) -> dict:
    """Return a sanitized plan or raise PlanValidationError."""
    if not isinstance(plan, dict):
        raise PlanValidationError("Scene plan must be an object")
    scenes = plan.get("scenes")
    if not isinstance(scenes, list) or not scenes:
        raise PlanValidationError("Scene plan needs a non-empty scenes list")
    if len(scenes) > _MAX_SCENES:
        raise PlanValidationError(f"Too many scenes (max {_MAX_SCENES})")

    clean_scenes: list[dict] = []
    for i, raw in enumerate(scenes, start=1):
        if not isinstance(raw, dict):
            raise PlanValidationError(f"Scene {i} must be an object")
        stype = _clean_str(raw.get("type"), 32)
        if stype not in SCENE_TYPES:
            raise PlanValidationError(f"Scene {i} has unsupported type {stype!r}")
        bullets = raw.get("bullets") or []
        if not isinstance(bullets, list):
            raise PlanValidationError(f"Scene {i} bullets must be a list")
        clean_scenes.append(
            {
                "id": i,
                "type": stype,
                "heading": _clean_str(raw.get("heading"), 120),
                "narration": _clean_str(raw.get("narration"), 700),
                "bullets": [_clean_str(b, 160) for b in bullets[:_MAX_BULLETS]],
                "formula": _clean_str(raw.get("formula"), 120),
                "duration": min(120, max(3, int(raw.get("duration") or 6))),
            }
        )

    complexity = _clean_str(plan.get("complexity"), 16)
    return {
        "concept": _clean_str(plan.get("concept"), 120) or "Concept",
        "complexity": complexity if complexity in COMPLEXITIES else "intermediate",
        "title": _clean_str(plan.get("title") or plan.get("concept"), 120),
        "scenes": clean_scenes,
    }


def build_scene_plan(script: dict) -> dict:
    """AI script dict -> validated scene plan."""
    return validate_scene_plan(script)


def render_source(plan: dict) -> str:
    """Generate Manim CE source from a *validated* plan (data embedded as a literal)."""
    plan = validate_scene_plan(plan)
    source = _TEMPLATE.replace("__PLAN_LITERAL__", repr(plan)).replace("__LATEX_AVAILABLE__", repr(bool(shutil.which("latex") and shutil.which("dvisvgm"))))
    _render_source_check(source)
    return source


def _render_source_check(source: str) -> None:
    """Belt-and-braces: our template shape only, syntax-checked (never executed here)."""
    if "__PLAN_LITERAL__" in source:
        raise PlanValidationError("Plan literal was not substituted")
    if "exec(" in source or "eval(" in source or "__import__" in source:
        raise PlanValidationError("Generated source failed shape check")
    compile(source, "<oraya_scene>", "exec")  # syntax check only


